"""Rebuild css/fonts-embedded.css, css/result-standalone.css and css/app-standalone.css from their sources.
Run after changing tokens.css, result.css, app.css or the font files:  python tools/make_standalone.py"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS, FONTS = ROOT / "css", ROOT / "fonts"

rules = []
for family, stem, weights in (("Noto Sans Hebrew", "NotoSansHebrew", (400, 500, 700)), ("JetBrains Mono", "JetBrainsMono", (500, 700))):
    for weight in weights:
        data = base64.b64encode((FONTS / f"{stem}-{weight}.woff2").read_bytes()).decode()
        rules.append(f'@font-face {{ font-family: "{family}"; font-style: normal; font-weight: {weight}; font-display: block;\n'
                     f'  src: url(data:font/woff2;base64,{data}) format("woff2"); }}')
embedded = ("/* HeOCR Android: the five bundled font files as data URIs, for a page that must be one self-contained string\n"
            "   (the WebView is filled with set_content, so relative URLs have nothing to resolve against).\n"
            "   Needs font-src data: in the page's Content-Security-Policy. Generated by tools/make_standalone.py. */\n"
            + "\n".join(rules) + "\n")
(CSS / "fonts-embedded.css").write_text(embedded, encoding="utf-8")

tokens, result, app = ((CSS / n).read_text(encoding="utf-8") for n in ("tokens.css", "result.css", "app.css"))
(CSS / "result-standalone.css").write_text(
    "/* HeOCR Android: result view, one self-contained file = tokens.css + fonts-embedded.css + result.css.\n"
    "   Generated by tools/make_standalone.py; edit the three sources instead. */\n" + tokens + "\n" + embedded + "\n" + result, encoding="utf-8")
(CSS / "app-standalone.css").write_text(
    "/* HeOCR Android: every screen, one self-contained file = tokens.css + fonts-embedded.css + result.css + app.css.\n"
    "   Generated by tools/make_standalone.py; edit the four sources instead. */\n" + tokens + "\n" + embedded + "\n" + result + "\n" + app, encoding="utf-8")
print("wrote fonts-embedded.css, result-standalone.css, app-standalone.css")
